const LANGS = ["en","zh","es","fr","ja"];
const LANG_LABELS = {en:"EN", zh:"中文", es:"ES", fr:"FR", ja:"日本語"};

function currentLang(){
  const saved = localStorage.getItem("gy-lang");
  return LANGS.includes(saved) ? saved : "en";
}

function applyLang(l){
  const dict = I18N[l] || I18N.en;
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const k = el.getAttribute("data-i18n");
    if (dict[k] !== undefined) el.textContent = dict[k];
  });
  document.querySelectorAll("[data-i18n-html]").forEach(el => {
    const k = el.getAttribute("data-i18n-html");
    if (dict[k] !== undefined) el.innerHTML = dict[k];
  });
  document.querySelectorAll("[data-i18n-attr]").forEach(el => {
    // format: data-i18n-attr="attr:key;attr:key"
    el.getAttribute("data-i18n-attr").split(";").forEach(pair => {
      const [attr, key] = pair.split(":").map(s => s.trim());
      if (attr && key && dict[key] !== undefined) el.setAttribute(attr, dict[key]);
    });
  });
  const page = document.body.getAttribute("data-page") || "home";
  const titleKey = "meta." + page;
  if (dict[titleKey]) document.title = dict[titleKey];
  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc && dict["meta.desc"]) metaDesc.setAttribute("content", dict["meta.desc"]);
  document.documentElement.setAttribute("lang", l === "zh" ? "zh-CN" : l);
  document.querySelectorAll(".lang-switch select").forEach(s => { s.value = l; });
  document.querySelectorAll("[data-show-lang]").forEach(el => {
    const langs = el.getAttribute("data-show-lang").split(",").map(s => s.trim());
    el.style.display = langs.includes(l) ? "" : "none";
  });
  localStorage.setItem("gy-lang", l);
}

